def get_scenario(scenario_id: str) -> ScenarioSpec:
    """Retrieve an immutable scenario specification from catalog."""
    if scenario_id not in SCENARIO_CATALOG:
        raise KeyError(f"Scenario '{scenario_id}' not found in catalog {SCENARIO_CATALOG.get('catalog_version', 'v1.0')}")
    return SCENARIO_CATALOG[scenario_id]


def list_scenarios(category: Optional[FaultCategory] = None, severity: Optional[Severity] = None) -> List[ScenarioSpec]:
    """List scenario specifications matching optional category and severity filters."""
    results = list(SCENARIO_CATALOG.values())
    if category:
        results = [s for s in results if s.category == category]
    if severity:
        results = [s for s in results if s.severity == severity]
    return results
